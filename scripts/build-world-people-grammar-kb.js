function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function stableJson(value) {
  if (Array.isArray(value)) return value.map(stableJson);
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(Object.keys(value).sort().map((key) => [key, stableJson(value[key])]));
}

function signature(value) {
  return crypto.createHash('sha256').update(JSON.stringify(stableJson(value))).digest('hex').slice(0, 16);
}

function canvasId(key) {
  return crypto.createHash('sha256').update(key).digest('hex').slice(0, 16);
}

function yamlString(value) {
  return JSON.stringify(String(value == null ? '' : value));
}

function cleanText(value) {
  return String(value == null ? '' : value).replace(/\r\n/g, '\n').replace(/\r/g, '\n').trim();
}

function inlineText(value) {
  return cleanText(value).replace(/\n+/g, ' ').replace(/\|/g, '\\|');
}

function sourcePages(source) {
  if (!source || typeof source !== 'object') return '';
  const parts = [];
  if (Array.isArray(source.printedPages) && source.printedPages.length) parts.push(`印刷页 ${source.printedPages.join('、')}`);
  if (Array.isArray(source.pdfPages) && source.pdfPages.length) parts.push(`PDF 页 ${source.pdfPages.join('、')}`);
  return parts.join('；');
}

function propertyList(name, values) {
  if (!values.length) return `${name}: []`;
  return [`${name}:`, ...values.map((value) => `  - ${yamlString(value)}`)].join('\n');
}

function callout(type, title, lines, collapsed = true) {
  const marker = collapsed ? '-' : '+';
  const body = lines
    .flatMap((line) => cleanText(line).split('\n'))
    .map((line) => `> ${line}`)
    .join('\n');
  return `> [!${type}]${marker} ${title}\n${body}`;
}

function formatPrimitive(value) {
  if (value === true) return '是';
  if (value === false) return '否';
  if (value == null) return '';
  return cleanText(value);
}

function renderStructured(value, indent = 0) {
  const pad = '  '.repeat(indent);
  if (value == null) return '';
  if (!Array.isArray(value) && typeof value !== 'object') return `${pad}${formatPrimitive(value)}`;
  if (Array.isArray(value)) {
    return value.map((item) => {
      if (item != null && typeof item === 'object') return `${pad}-\n${renderStructured(item, indent + 1)}`;
      return `${pad}- ${formatPrimitive(item)}`;
    }).join('\n');
  }
  return Object.entries(value)
    .filter(([key]) => key !== 'answer')
    .map(([key, item]) => {
      const label = FIELD_LABELS[key] || key;
      if (item != null && typeof item === 'object') return `${pad}- **${label}**\n${renderStructured(item, indent + 1)}`;
      return `${pad}- **${label}**：${formatPrimitive(item)}`;
    })
    .join('\n');
}

function renderOptions(options) {
  if (!Array.isArray(options) || !options.length) return '';
  return options.map((option) => `- **${inlineText(option.key || '')}** ${cleanText(option.text || option.ru || option.zh || '')}`).join('\n');
}

function renderFeedback(feedback) {
  if (!feedback || typeof feedback !== 'object') return [];
  return Object.entries(feedback).map(([key, value]) => `${FIELD_LABELS[key] || key}：${formatPrimitive(value)}`);
}

function renderAssessment(item, heading, index) {
  if (!item || typeof item !== 'object') return '';
  const title = cleanText(item.title || item.id || `${heading} ${index + 1}`);
  const sections = [`### ${title}`, '', cleanText(item.prompt || item.question || '')];
  const options = renderOptions(item.options);
  if (options) sections.push('', options);
  const answerLines = [];
  if (item.answer != null) answerLines.push(`答案：**${formatPrimitive(item.answer)}**`);
  answerLines.push(...renderFeedback(item.feedback));
  if (item.retry) {
    answerLines.push('', '同类再练：', cleanText(item.retry.prompt || ''));
    const retryOptions = renderOptions(item.retry.options);
    if (retryOptions) answerLines.push(retryOptions);
    if (item.retry.answer != null) answerLines.push(`同类再练答案：**${formatPrimitive(item.retry.answer)}**`);
  }
  if (answerLines.length) sections.push('', callout('success', '答案与反馈', answerLines, true));
  if (item.hint) sections.push('', callout('tip', '提示', [item.hint], true));
  return sections.filter((line, position, all) => !(line === '' && all[position - 1] === '')).join('\n');
}

function renderDiagnostic(diagnostic) {
  if (!diagnostic || typeof diagnostic !== 'object') return '';
  const { answer, feedback, ...publicData } = diagnostic;
  const sections = [renderStructured(publicData)];
  const answerLines = [];
  if (answer != null) answerLines.push(`答案：**${formatPrimitive(answer)}**`);
  if (typeof feedback === 'string') answerLines.push(`反馈：${cleanText(feedback)}`);
  else answerLines.push(...renderFeedback(feedback));
  if (answerLines.length) sections.push('', callout('success', '诊断答案与反馈', answerLines, true));
  return sections.join('\n');
}

function renderExamples(examples) {
  if (!Array.isArray(examples) || !examples.length) return '本阶段没有单独列出的例句。';
  return examples.map((example, index) => {
    const lines = [`${index + 1}. **${cleanText(example.ru || '')}**`];
    if (example.zh) lines.push(`   - 中文：${cleanText(example.zh)}`);
    if (example.analysis) lines.push(`   - 为什么：${cleanText(example.analysis)}`);
    const pages = sourcePages(example.source);
    if (pages) lines.push(`   - 来源：${pages}`);
    if (example.sourceType) lines.push(`   - 层级：${example.sourceType}`);
    return lines.join('\n');
  }).join('\n');
}

function renderSignals(signals) {
  if (!Array.isArray(signals) || !signals.length) return '本阶段没有单独列出的信号词。';
  return signals.map((signal, index) => {
    const words = Array.isArray(signal.words) ? signal.words.join('、') : cleanText(signal.words || signal.word || '');
    return [
      `${index + 1}. **${words}**`,
      `   - 可以使用：${cleanText(signal.validWhen || '')}`,
      `   - 不能单独决定答案：${cleanText(signal.failsWhen || '')}`
    ].join('\n');
  }).join('\n');
}

function renderContrasts(contrasts) {
  if (!Array.isArray(contrasts) || !contrasts.length) return '本阶段没有单独列出的正反对比。';
  return contrasts.map((contrast, index) => [
    `${index + 1}. **${cleanText(contrast.left || '')}**`,
    `   - 对照：**${cleanText(contrast.right || '')}**`,
    `   - 分析：${cleanText(contrast.analysis || '')}`
  ].join('\n')).join('\n');
}

function renderErrors(errors) {
  if (!Array.isArray(errors) || !errors.length) return '本阶段没有单独列出的易错说明。';
  return errors.map((error, index) => `${index + 1}. ${cleanText(typeof error === 'string' ? error : error.text || renderStructured(error))}`).join('\n');
}

function renderEvidence(stage) {
  const blocks = [];
  if (stage.sourceRule) {
    blocks.push(callout('quote', '原书规则', [
      stage.sourceRule.label ? `标签：${stage.sourceRule.label}` : '',
      stage.sourceRule.ru ? `俄语：${stage.sourceRule.ru}` : '',
      stage.sourceRule.zh ? `中文：${stage.sourceRule.zh}` : '',
      sourcePages(stage.sourceRule.source) ? `页码：${sourcePages(stage.sourceRule.source)}` : '',
      stage.sourceRule.sourceType ? `层级：${stage.sourceRule.sourceType}` : ''
    ].filter(Boolean), true));
  }
  if (stage.sourceEvidence) {
    blocks.push(callout('quote', '原书逐字证据', [
      stage.sourceEvidence.ru ? `俄语：${stage.sourceEvidence.ru}` : '',
      stage.sourceEvidence.zh ? `中文：${stage.sourceEvidence.zh}` : '',
      sourcePages(stage.sourceEvidence.source) ? `页码：${sourcePages(stage.sourceEvidence.source)}` : '',
      stage.sourceEvidence.sourceType ? `层级：${stage.sourceEvidence.sourceType}` : ''
    ].filter(Boolean), true));
  }
  return blocks.join('\n\n');
}

function renderStage(stage) {
  const explanation = (stage.teacherExplanation || []).map((paragraph) => cleanText(paragraph)).filter(Boolean).join('\n\n');
  const checks = (stage.checks || []).map((check, index) => renderAssessment(check, '随堂题', index)).filter(Boolean).join('\n\n');
  const exerciseIds = Array.isArray(stage.exerciseIds) && stage.exerciseIds.length
    ? stage.exerciseIds.map((id) => `- ${id}`).join('\n')
    : '- 本阶段没有安全映射的正式题。';
  return [
    `## ${stage.number}. ${cleanText(stage.title || stage.id)}`,
    '',
    `**本阶段要回答：** ${cleanText(stage.question || '')}`,
    '',
    stage.entry && stage.entry.ru ? `**先看例子：** ${cleanText(stage.entry.ru)}` : '',
    stage.entry && stage.entry.prompt ? `\n${cleanText(stage.entry.prompt)}` : '',
    '',
    '### 老师讲解',
    '',
    explanation || '本阶段讲解以 Reader 正式数据为准。',
    '',
    '### 原书例句与分析',
    '',
    renderExamples(stage.sourceExamples),
    '',
    '### 正反对比',
    '',
    renderContrasts(stage.contrasts),
    '',
    '### 判断线索与失效边界',
    '',
    renderSignals(stage.signals),
    '',
    '### 常见误区',
    '',
    renderErrors(stage.commonErrors),
    '',
    '### 随堂题',
    '',
    checks || '本阶段没有单独列出的随堂题。',
    '',
    '### 正式题入口',
    '',
    exerciseIds,
    '',
    renderEvidence(stage)
  ].filter((line, position, all) => !(line === '' && all[position - 1] === '')).join('\n');
}

