function scanCards() {
  const cards = new Map();
  for (const chapterId of ['gl1', 'gl2', 'gl3', 'gl4', 'gl5']) {
    const directory = path.join(LEARNING_ROOT, chapterId);
    for (const name of fs.readdirSync(directory).filter((item) => /^section-.*\.json$/.test(item))) {
      const filePath = path.join(directory, name);
      const card = readJson(filePath);
      card.__sourcePath = path.relative(PROJECT_ROOT, filePath).replace(/\\/g, '/');
      cards.set(card.sectionId, card);
    }
  }
  return cards;
}

function validateGraph(graph, cards) {
  const allowedTypes = new Set(graph.relationTypes || []);
  const order = graph.learningOrder || [];
  if (order.length !== 32 || new Set(order).size !== 32) throw new Error('learningOrder 必须恰好包含 32 个唯一卡片 ID');
  for (const sectionId of order) if (!cards.has(sectionId)) throw new Error(`knowledge-graph 引用了不存在的卡片：${sectionId}`);
  const conceptIds = new Set();
  for (const concept of graph.concepts || []) {
    if (!concept.id || !concept.label || !concept.summary) throw new Error('核心概念缺少 id、label 或 summary');
    if (conceptIds.has(concept.id)) throw new Error(`重复核心概念：${concept.id}`);
    conceptIds.add(concept.id);
  }
  for (const relation of graph.sectionRelations || []) {
    if (!cards.has(relation.from) || !cards.has(relation.to)) throw new Error(`卡片关系存在无效端点：${relation.from} -> ${relation.to}`);
    if (!allowedTypes.has(relation.type)) throw new Error(`不支持的关系类型：${relation.type}`);
    if (!cleanText(relation.reason)) throw new Error(`卡片关系缺少原因：${relation.from} -> ${relation.to}`);
  }
  const conceptCounts = new Map([...conceptIds].map((id) => [id, 0]));
  for (const relation of graph.conceptRelations || []) {
    if (!cards.has(relation.sectionId)) throw new Error(`概念关系引用不存在的卡片：${relation.sectionId}`);
    if (!conceptIds.has(relation.conceptId)) throw new Error(`概念关系引用不存在的概念：${relation.conceptId}`);
    if (!cleanText(relation.reason)) throw new Error(`概念关系缺少原因：${relation.sectionId} -> ${relation.conceptId}`);
    conceptCounts.set(relation.conceptId, conceptCounts.get(relation.conceptId) + 1);
  }
  for (const [conceptId, count] of conceptCounts) if (count < 2) throw new Error(`核心概念 ${conceptId} 只连接 ${count} 张卡，不应进入总图`);
}

function sectionRelationsFor(graph, sectionId) {
  return (graph.sectionRelations || []).filter((relation) => relation.from === sectionId || relation.to === sectionId);
}

function conceptRelationsFor(graph, sectionId) {
  return (graph.conceptRelations || []).filter((relation) => relation.sectionId === sectionId);
}

function renderCardNote(card, graph, cards, conceptsById) {
  const sectionRelations = sectionRelationsFor(graph, card.sectionId);
  const conceptRelations = conceptRelationsFor(graph, card.sectionId);
  const conceptLinks = conceptRelations.map((relation) => conceptLink(conceptsById.get(relation.conceptId)));
  const prerequisites = sectionRelations
    .filter((relation) => relation.type === 'prerequisite' && relation.to === card.sectionId)
    .map((relation) => cardLink(cards.get(relation.from)));
  const relatedLinks = sectionRelations.map((relation) => {
    const otherId = relation.from === card.sectionId ? relation.to : relation.from;
    return cardLink(cards.get(otherId));
  });
  const chapter = graph.chapters.find((item) => item.id === card.chapterId);
  const sourceStatus = card.reviewStatus || ((card.sources || []).some((source) => source.status === 'needs-review') ? 'needs-review' : 'not-declared');
  const frontmatter = [
    '---',
    'type: world-people-grammar-card',
    'book: "В мире людей - 语法词汇"',
    `section: ${yamlString(card.sectionId)}`,
    `chapter: ${yamlString(card.chapterId)}`,
    `chapter_label: ${yamlString(chapter.label)}`,
    `title: ${yamlString(card.titleZh)}`,
    `title_ru: ${yamlString(card.titleRu || '')}`,
    `stage_count: ${(card.stages || []).length}`,
    `estimated_minutes: ${yamlString(card.estimatedMinutes?.core || '')}`,
    `review_status: ${yamlString(card.reviewStatus || 'not-declared')}`,
    `source_status: ${yamlString(sourceStatus)}`,
    'reader_status: merged',
    `generated_from: ${yamlString(card.__sourcePath)}`,
    `generated_by: ${yamlString(GENERATOR_ID)}`,
    `generated_signature: ${yamlString(signature(card))}`,
    propertyList('concepts', conceptLinks),
    propertyList('prerequisites', prerequisites),
    propertyList('related', [...new Set(relatedLinks)]),
    'tags:',
    '  - 俄语/语法词汇',
    '  - В-мире-людей',
    '  - 知识点卡片',
    'aliases:',
    `  - ${yamlString(card.sectionId)}`,
    '---'
  ].join('\n');
  const relationText = sectionRelations.length
    ? sectionRelations.map((relation) => {
      const otherId = relation.from === card.sectionId ? relation.to : relation.from;
      return `- **${RELATION_LABELS[relation.type]}** ${cardLink(cards.get(otherId))}：${relation.reason}`;
    }).join('\n')
    : '- 当前关系底稿没有为本卡建立直接跨卡关系。';
  const conceptText = conceptRelations.length
    ? conceptRelations.map((relation) => `- ${conceptLink(conceptsById.get(relation.conceptId))}：${relation.reason}`).join('\n')
    : '- 当前关系底稿没有为本卡建立共享概念。';
  const objectives = (card.objectives || []).map((objective) => `- ${cleanText(objective)}`).join('\n') || '- 以卡片中心问题为学习目标。';
  const stages = (card.stages || []).map(renderStage).join('\n\n---\n\n');
  const finalCheck = card.finalCheck ? renderAssessment(card.finalCheck, '综合判断', 0) : '本卡没有单独列出的综合判断题。';
  const transferTasks = (card.transferTasks || []).map((task, index) => renderAssessment(task, '迁移任务', index)).join('\n\n') || '本卡没有单独列出的迁移任务。';
  const sourceLines = (card.sources || []).map((source, index) => [
    `${index + 1}. ${cleanText(source.label || source.sourceType || '来源')}`,
    source.sourceType ? `   - 层级：${source.sourceType}` : '',
    source.status ? `   - 状态：${source.status}` : '',
    sourcePages(source.source) ? `   - 页码：${sourcePages(source.source)}` : ''
  ].filter(Boolean).join('\n')).join('\n') || '本卡没有额外来源清单。';
  const riskLines = (card.riskRecord || []).map((risk) => `- ${cleanText(risk)}`).join('\n') || '- 当前卡片没有单独列出的风险记录。';
  return [
    frontmatter,
    '',
    MARKDOWN_MARKER,
    '',
    `# ${card.sectionId} ${cleanText(card.titleZh)}`,
    '',
    card.titleRu ? `**俄语标题：** ${cleanText(card.titleRu)}` : '',
    '',
    callout('abstract', '这张卡解决什么', [card.problem || card.mindMapQuestion || '请从中心问题进入。'], false),
    '',
    card.scopeNote ? callout('warning', '适用边界', [card.scopeNote], true) : '',
    '',
    '## 学习目标',
    '',
    objectives,
    '',
    '## 卡内树形思维导图',
    '',
    renderMindMap(card),
    '',
    card.diagnostic ? '## 入门诊断\n\n' + renderDiagnostic(card.diagnostic) : '',
    '',
    card.decisionFlow ? '## 判断流程\n\n' + renderStructured(card.decisionFlow) : '',
    '',
    card.mindMapWalkthrough ? '## 全卡串讲\n\n' + renderStructured(card.mindMapWalkthrough) : '',
    '',
    '---',
    '',
    '# 完整阶段讲解',
    '',
    stages,
    '',
    '---',
    '',
    '## 综合判断',
    '',
    finalCheck,
    '',
    '## 迁移任务',
    '',
    transferTasks,
    '',
    card.summaryTable ? '## 全卡汇总\n\n' + renderStructured(card.summaryTable) : '',
    '',
    '## 核心概念',
    '',
    conceptText,
    '',
    '## 跨卡关系',
    '',
    relationText,
    '',
    '## Reader 入口',
    '',
    `打开白夜俄语 Reader，进入《В мире людей - 语法词汇》，选择 **${card.sectionId} ${cleanText(card.titleZh)}**。答题记录和正式学习进度只保存在 Reader。`,
    '',
    callout('quote', '来源清单', [sourceLines], true),
    '',
    callout('warning', '风险记录', [riskLines], true)
  ].filter((line, position, all) => !(line === '' && all[position - 1] === '')).join('\n') + '\n';
}

