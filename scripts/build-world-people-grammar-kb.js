function chapterLayout(graph, cards) {
  const layouts = {};
  let x = -2100;
  for (const chapter of graph.chapters) {
    const memberCount = graph.learningOrder.filter((sectionId) => cards.get(sectionId).chapterId === chapter.id).length;
    const columns = memberCount >= 8 ? 3 : memberCount >= 4 ? 2 : 1;
    const width = columns * 430 + (columns + 1) * 60;
    const rows = Math.ceil(memberCount / columns);
    layouts[chapter.id] = { x, y: 300, width, height: 250 + rows * 250, columns, color: chapter.color };
    x += width + 260;
  }
  return layouts;
}

function buildCanvas(graph, cards, conceptsById, outputRoot) {
  const oldPath = path.join(outputRoot, '02-全书知识图谱.canvas');
  let oldCanvas = { nodes: [], edges: [] };
  if (fs.existsSync(oldPath)) {
    try { oldCanvas = readJson(oldPath); } catch { oldCanvas = { nodes: [], edges: [] }; }
  }
  const oldNodes = new Map((oldCanvas.nodes || []).map((node) => [node.id, node]));
  const generatedNodeIds = new Set();
  const generatedEdgeIds = new Set();
  const nodes = [];
  const edges = [];
  const nodeByKey = new Map();

  function addNode(key, node) {
    const id = canvasId(`node:${key}`);
    generatedNodeIds.add(id);
    const previous = oldNodes.get(id);
    const geometry = previous ? {
      x: previous.x,
      y: previous.y,
      width: previous.width,
      height: previous.height
    } : {};
    const next = { id, ...node, ...geometry };
    nodes.push(next);
    nodeByKey.set(key, next);
    return next;
  }

  function edgeSides(from, to) {
    const fromCenterX = from.x + from.width / 2;
    const fromCenterY = from.y + from.height / 2;
    const toCenterX = to.x + to.width / 2;
    const toCenterY = to.y + to.height / 2;
    if (Math.abs(toCenterX - fromCenterX) > Math.abs(toCenterY - fromCenterY)) {
      return toCenterX > fromCenterX
        ? { fromSide: 'right', toSide: 'left' }
        : { fromSide: 'left', toSide: 'right' };
    }
    return toCenterY > fromCenterY
      ? { fromSide: 'bottom', toSide: 'top' }
      : { fromSide: 'top', toSide: 'bottom' };
  }

  function addEdge(key, from, to, label, color) {
    const id = canvasId(`edge:${key}`);
    generatedEdgeIds.add(id);
    edges.push({ id, fromNode: from.id, toNode: to.id, ...edgeSides(from, to), toEnd: 'arrow', label, color });
  }

  const layouts = chapterLayout(graph, cards);
  const root = addNode('root', {
    type: 'file',
    file: '语法/В мире людей·语法词汇知识库/00-知识库总览.md',
    x: -2750,
    y: -1150,
    width: 520,
    height: 260,
    color: '6'
  });
  addNode('concept-group', { type: 'group', x: -1900, y: -1500, width: 6100, height: 1200, label: '跨卡核心概念', color: '6' });
  graph.concepts.forEach((concept, index) => {
    const column = index % 4;
    const row = Math.floor(index / 4);
    const node = addNode(`concept:${concept.id}`, {
      type: 'file',
      file: vaultConceptPath(concept),
      x: -1800 + column * 1450,
      y: -1360 + row * 270,
      width: 1320,
      height: 210,
      color: '6'
    });
    addEdge(`root-concept:${concept.id}`, root, node, '核心概念', '6');
  });
  for (const chapter of graph.chapters) {
    const layout = layouts[chapter.id];
    addNode(`group:${chapter.id}`, { type: 'group', x: layout.x, y: layout.y, width: layout.width, height: layout.height, label: chapter.label, color: chapter.color });
    const anchor = addNode(`chapter:${chapter.id}`, {
      type: 'text',
      x: layout.x + 50,
      y: layout.y + 70,
      width: layout.width - 100,
      height: 90,
      text: `# ${chapter.label}\n点击卡片进入完整知识库笔记。`,
      color: chapter.color
    });
    addEdge(`root-chapter:${chapter.id}`, root, anchor, '章节', chapter.color);
    const members = graph.learningOrder.filter((sectionId) => cards.get(sectionId).chapterId === chapter.id);
    members.forEach((sectionId, index) => {
      const card = cards.get(sectionId);
      const column = index % layout.columns;
      const row = Math.floor(index / layout.columns);
      const cardWidth = Math.floor((layout.width - (layout.columns + 1) * 60) / layout.columns);
      const node = addNode(`section:${sectionId}`, {
        type: 'file',
        file: vaultCardPath(card),
        x: layout.x + 60 + column * (cardWidth + 60),
        y: layout.y + 200 + row * 250,
        width: cardWidth,
        height: 190,
        color: chapter.color
      });
      addEdge(`chapter-section:${chapter.id}:${sectionId}`, anchor, node, '本章知识点', chapter.color);
    });
  }
  for (const relation of graph.sectionRelations) {
    addEdge(
      `section-relation:${relation.from}:${relation.to}:${relation.type}`,
      nodeByKey.get(`section:${relation.from}`),
      nodeByKey.get(`section:${relation.to}`),
      RELATION_LABELS[relation.type],
      RELATION_COLORS[relation.type]
    );
  }
  for (const relation of graph.conceptRelations) {
    addEdge(
      `concept-relation:${relation.conceptId}:${relation.sectionId}`,
      nodeByKey.get(`concept:${relation.conceptId}`),
      nodeByKey.get(`section:${relation.sectionId}`),
      '共同概念',
      '6'
    );
  }
  const manualNodes = (oldCanvas.nodes || []).filter((node) => !generatedNodeIds.has(node.id));
  const allNodeIds = new Set([...nodes, ...manualNodes].map((node) => node.id));
  const manualEdges = (oldCanvas.edges || []).filter((edge) => !generatedEdgeIds.has(edge.id) && allNodeIds.has(edge.fromNode) && allNodeIds.has(edge.toNode));
  return { nodes: [...nodes, ...manualNodes], edges: [...edges, ...manualEdges] };
}

