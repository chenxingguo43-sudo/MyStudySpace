function isManagedText(content) {
  return content.includes(GENERATOR_ID);
}

function writeManagedFile(filePath, content, expected, options = {}) {
  expected.add(path.resolve(filePath));
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  if (fs.existsSync(filePath)) {
    const oldContent = fs.readFileSync(filePath, 'utf8');
    if (options.preserveUnmanaged && !isManagedText(oldContent)) return false;
    if (!options.allowJsonCanvas && !isManagedText(oldContent)) throw new Error(`拒绝覆盖不含生成标记的文件：${filePath}`);
    if (oldContent === content) return false;
  }
  fs.writeFileSync(filePath, content, 'utf8');
  return true;
}

function listFiles(root) {
  if (!fs.existsSync(root)) return [];
  return fs.readdirSync(root, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(root, entry.name);
    return entry.isDirectory() ? listFiles(fullPath) : [fullPath];
  });
}

function buildKnowledgeBase(options = {}) {
  const outputRoot = path.resolve(options.outputRoot || DEFAULT_OUTPUT_ROOT);
  const graph = readJson(GRAPH_PATH);
  const cards = scanCards();
  validateGraph(graph, cards);
  const conceptsById = new Map(graph.concepts.map((concept) => [concept.id, concept]));
  const expected = new Set();
  const changed = [];

  function write(relativePath, content, fileOptions) {
    const filePath = path.join(outputRoot, relativePath);
    if (writeManagedFile(filePath, content, expected, fileOptions)) changed.push(relativePath);
  }

  for (const sectionId of graph.learningOrder) {
    const card = cards.get(sectionId);
    write(path.join('知识点', chapterFolder(card.chapterId), `${sectionId}.md`), renderCardNote(card, graph, cards, conceptsById));
  }
  for (const concept of graph.concepts) {
    write(path.join('核心概念', `${conceptFileName(concept)}.md`), renderConceptNote(concept, graph, cards));
  }
  write('00-知识库总览.md', renderOverview(graph, cards));
  write('01-知识卡片管理.base', renderBase());
  const canvas = buildCanvas(graph, cards, conceptsById, outputRoot);
  write('02-全书知识图谱.canvas', JSON.stringify(canvas, null, 2) + '\n', { allowJsonCanvas: true });
  write('README.md', renderReadme(graph));
  write(path.join('进度', '学习进度快照.md'), renderProgressBoundary(), { preserveUnmanaged: true });

  const staleManaged = listFiles(outputRoot)
    .filter((filePath) => !expected.has(path.resolve(filePath)))
    .filter((filePath) => {
      if (!/\.(md|base|canvas)$/.test(filePath)) return false;
      try { return isManagedText(fs.readFileSync(filePath, 'utf8')); } catch { return false; }
    })
    .map((filePath) => path.relative(outputRoot, filePath).replace(/\\/g, '/'));
  const report = {
    generator: GENERATOR_ID,
    cardCount: graph.learningOrder.length,
    conceptCount: graph.concepts.length,
    sectionRelationCount: graph.sectionRelations.length,
    conceptRelationCount: graph.conceptRelations.length,
    canvasNodeCount: canvas.nodes.length,
    canvasEdgeCount: canvas.edges.length,
    changedFiles: changed,
    staleManagedFiles: staleManaged
  };
  return { outputRoot, graph, cards, canvas, report };
}

function parseArgs(argv) {
  const args = { outputRoot: DEFAULT_OUTPUT_ROOT, check: false };
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--check') args.check = true;
    else if (argv[index] === '--output') {
      if (!argv[index + 1]) throw new Error('--output 需要目录参数');
      args.outputRoot = path.resolve(argv[index + 1]);
      index += 1;
    } else throw new Error(`不支持的参数：${argv[index]}`);
  }
  return args;
}

if (require.main === module) {
  try {
    const args = parseArgs(process.argv.slice(2));
    if (args.check && !fs.existsSync(args.outputRoot)) throw new Error(`知识库目录不存在：${args.outputRoot}`);
    const result = buildKnowledgeBase({ outputRoot: args.outputRoot });
    if (args.check && result.report.changedFiles.length) {
      console.error('知识库不是最新生成状态：');
      result.report.changedFiles.forEach((file) => console.error(`- ${file}`));
      process.exitCode = 1;
    } else {
      console.log(`知识库完成：${result.report.cardCount} 张卡，${result.report.conceptCount} 个核心概念。`);
      console.log(`Canvas：${result.report.canvasNodeCount} 个节点，${result.report.canvasEdgeCount} 条连线。`);
      console.log(`本次更新：${result.report.changedFiles.length} 个文件。`);
      if (result.report.staleManagedFiles.length) {
        console.log('检测到未自动删除的旧生成文件：');
        result.report.staleManagedFiles.forEach((file) => console.log(`- ${file}`));
      }
    }
  } catch (error) {
    console.error(error.stack || error.message);
    process.exitCode = 1;
  }
}

