// Keep the generator idempotent even when an earlier draft already appended a section.
for (const exercise of chapter.exercises) {
  const seenSections = new Set();
  exercise.detailed_explanation = exercise.detailed_explanation
    .split('\n\n')
    .filter((section) => {
      const heading = section.match(/^【[^\n]+】/)?.[0] || section;
      if (seenSections.has(heading)) return false;
      seenSections.add(heading);
      return true;
    })
    .join('\n\n');
}

