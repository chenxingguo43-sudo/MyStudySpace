function source(file, section, pages) {
  return { kind: 'grammar-book', label: '新编俄语语法', file, section, pages };
}
function supplement() { return { kind: 'supplement-example', label: '补充例句' }; }
function lesson(card, item, index) {
  const examples = [{ ru: item.example.ru, zh: item.example.zh, source: supplement() }];
  return {
    id: `l${index + 1}`,
    title: item.title,
    scope: 'core',
    meaning: item.meaning,
    conditions: item.conditions,
    structure: item.structure,
    caseChanges: item.caseChanges,
    examples,
    boundaries: item.boundaries,
    instantChecks: [{
      id: `l${index + 1}-check`, type: 'judgment', prompt: item.check,
      answer: true, rationale: item.rationale, source: card.source
    }],
    sources: [card.source]
  };
}
function makeCard(config) {
  const card = {
    id: config.id, partId: 'p2', knowledgePointId: config.id,
    title: config.title, exerciseIds: config.exerciseIds, overview: config.overview,
    decisionSteps: config.decisionSteps, reviewStatus: 'approved',
    quickReference: { semanticQuestions: config.questions, structures: config.structures },
    source: source(config.file, config.section, config.pages)
  };
  card.lessons = config.lessons.map((item, index) => lesson(card, item, index));
  card.relatedExtensions = [];
  card.checks = config.lessons.slice(0, 3).map((item, index) => ({
    id: `review-${index + 1}`, type: 'judgment', prompt: item.check,
    answer: true, rationale: item.rationale, source: card.source
  }));
  card.rules = config.lessons.map(item => ({ text: `${item.structure}：${item.meaning}`, source: card.source }));
  card.comparisons = [{ left: config.compare.left, right: config.compare.right, note: config.compare.note, source: { kind: 'learning-explanation', label: '学习讲解' } }];
  card.examples = config.lessons.map(item => ({ ...item.example, source: supplement() }));
  card.pitfalls = config.pitfalls;
  card.sources = [card.source];
  delete card.source;
  return card;
}
