// Better approach: replace the placeholder content directly
function replacePlaceholder(content, sectionHeader, newContent) {
  const start = content.indexOf(sectionHeader);
  if (start === -1) return content;

  const afterHeader = content.indexOf('\n', start) + 1;
  const endMarker = '\n## ';
  const end = content.indexOf(endMarker, afterHeader);
  const sectionEnd = end > 0 ? end : content.length;

  return content.substring(0, afterHeader) + newContent + content.substring(sectionEnd);
}

