let total = 0;
for (const [chFile, explanations] of Object.entries(chapters)) {
  const path = 'data/textbook/reading_speaking/' + chFile + '.json';
  if (!fs.existsSync(path)) continue;
  const ch = JSON.parse(fs.readFileSync(path, 'utf8'));
  if (!ch.exercises) continue;

  let updated = 0;
  for (const ex of ch.exercises) {
    if (!ex.detailed_explanation && ex.answer && explanations[ex.num]) {
      ex.detailed_explanation = explanations[ex.num];
      updated++;
    }
  }

  if (updated > 0) {
    fs.writeFileSync(path, JSON.stringify(ch, null, 2), 'utf8');
    total += updated;
    console.log(chFile + ': ' + updated + ' explanations added');
  }
}
console.log('Total added:', total);
