// ─── 6. 构建干净 lemma 频率 ───
var cleanFreq={};
Object.keys(surfaceFreq).forEach(function(w){
  var lw=w.toLowerCase();
  if(stops[lw])return;
  var nw=norm(w);
  if(map[nw])return;           // 映射表已覆盖
  if(lookup[nw])return;        // 词典已覆盖
  var guesses=morphologyGuess(nw),found=false;
  for(var i=0;i<guesses.length;i++){if(lookup[guesses[i]]){found=true;break}}
  if(found)return;             // 规则引擎能搞定

  var lemma=nw;
  if(guesses.length>0)lemma=guesses[0];

  if(nameSet[lemma])return;    // 跳过人名
  if(mtFix[lemma])lemma=mtFix[lemma]; // 修正拼写错误
  if(lemma.length<3)return;

  cleanFreq[lemma]=(cleanFreq[lemma]||0)+surfaceFreq[w];
});

var sorted=Object.keys(cleanFreq).sort(function(a,b){return cleanFreq[b]-cleanFreq[a]});

// ─── 7. 二次去噪 ───
var isTransliteration=function(l){
  // 中文音译特征：辅音弱、元音简单、无辅音簇
  if(/^[цчшщж][ьяеио][а-я]?$/.test(l))return true;
  if(/^[а-я]?[цчшщж][а-яё]{1,2}$/.test(l))return true;
  return false;
};

var final=[];
for(var i=0;i<sorted.length;i++){
  var l=sorted[i];
  if(isTransliteration(l))continue;
  // 跳过含 ты/вы 变位的词(已在stopWords)
  if(nameSet[l])continue;
  // 2字母跳过
  if(l.length<3)continue;
  final.push({lemma:l,freq:cleanFreq[l]});
}

// ─── 8. 写文件 ───
