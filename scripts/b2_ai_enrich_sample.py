def append_content(file_path: str, word: str, content: str):
    """读取 .md 文件，在末尾追加详细内容。"""
    if not os.path.isfile(file_path):
        print(f"[错误] 文件不存在: {file_path}")
        return False

    with open(file_path, "r", encoding="utf-8") as f:
        existing = f.read()

    # 检查是否已经追加过（防重复）
    if "## 📝 详细释义" in existing:
        print(f"[跳过] {word} — 已包含详细内容，不重复追加。")
        return False

    # 确保末尾有换行
    if not existing.endswith("\n"):
        existing += "\n"

    new_content = existing + "\n" + content + "\n"

    with open(file_path, "w", encoding="utf-8") as f:
        f.write(new_content)

    print(f"[完成] {word} — 内容已追加到 {file_path}")
    return True


def main():
    print("=" * 60)
    print("B2 词汇详细内容追加脚本 (4 个测试词)")
    print("=" * 60)

    success = 0
    for word, path in WORD_FILES.items():
        if word in CONTENT:
            if append_content(path, word, CONTENT[word]):
                success += 1
        else:
            print(f"[警告] 没有找到 {word} 的内容数据。")

    print("-" * 60)
    print(f"处理完成：共 {len(WORD_FILES)} 个词，成功追加 {success} 个。")


if __name__ == "__main__":
    main()
