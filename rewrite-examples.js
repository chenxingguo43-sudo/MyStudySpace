function isAbstractNoun(meaning) {
    // 抽象名词不应该用"买了""看到了"等具体模板
    return /危险|安全|命运|自由|和平|战争|幸福|痛苦|希望|失望|勇气|信心|力量|知识|真理|谎言|责任|权利|义务|经验|能力|机会|条件|原因|结果|方法|态度|精神|文化|传统|道德|法律|政治|经济|科学|技术|艺术|教育|健康|疾病|生命|死亡|成功|失败|进步|退步|变化|发展|未来|过去|现在|时间|空间|速度|温度|颜色|声音|味道|感觉|情感|思想|记忆|想象|现实|梦想|秘密|真理|谎言|命令|秩序|混乱|禁止|剥夺|巩固|加强|削弱|肥沃|贫瘠/.test(meaning);
}

function generateExamples(type, word, meaning, gender, aspect) {
    const seed = hashStr(word);
    let primary = meaning.split(/[,，、；;/]/)[0].trim();
    // 去掉末尾的"的"避免模板中重复（如"整洁的的裙子"）
    if (primary.endsWith('的') && primary.length > 1) {
        primary = primary.slice(0, -1);
    }
    let templates, examples;

    switch (type) {
        case 'verb': {
            const verbTemplates = getVerbTemplates(meaning);
            templates = pickN(verbTemplates, 3, seed);
            examples = templates.map(t => {
                let ru;
                try { ru = t.make(word); } catch(e) {
                    ru = `Я ча́сто ${conjPresent(word,1,'sg')} — э́то полéзно.`;
                }
                return { ru, zh: t.zh.replace('{meaning}', primary) };
            });
            break;
        }
        case 'noun': {
            const g = gender === 'feminine' ? 'f' : gender === 'neuter' ? 'n' : 'm';
            const abstract = isAbstractNoun(meaning);
            const nounPool = abstract ? ABSTRACT_NOUN_TEMPLATES : NOUN_TEMPLATES;
            templates = pickN(nounPool, 3, seed);
            examples = templates.map(t => {
                let ru;
                try { ru = t.make(word, g); } catch(e) {
                    ru = `Э́тот ${word} óчень ва́жен для háшей жи́зни.`;
                }
                return { ru, zh: t.zh.replace('{meaning}', primary) };
            });
            break;
        }
        case 'adj': {
            templates = pickN(ADJ_TEMPLATES, 3, seed);
            examples = templates.map(t => {
                let ru;
                try { ru = t.make(word); } catch(e) {
                    ru = `Э́то óчень ${strip(word)} — мне нрáвится.`;
                }
                return { ru, zh: t.zh.replace('{meaning}', primary) };
            });
            break;
        }
        case 'adv': {
            templates = pickN(ADV_TEMPLATES, 3, seed);
            examples = templates.map(t => {
                let ru;
                try { ru = t.make(word); } catch(e) {
                    ru = `Он ${strip(word)} говори́т.`;
                }
                return { ru, zh: t.zh.replace('{meaning}', primary) };
            });
            break;
        }
        case 'particle':
        case 'func': {
            templates = pickN(PARTICLE_TEMPLATES, 3, seed);
            examples = templates.map(t => ({
                ru: t.make(),
                zh: t.zh.replace('{meaning}', primary)
            }));
            break;
        }
        default: {
            templates = pickN(ADJ_TEMPLATES, 3, seed);
            examples = templates.map(t => {
                let ru;
                try { ru = t.make(word); } catch(e) { ru = `Э́то ${strip(word)}.`; }
                return { ru, zh: t.zh.replace('{meaning}', primary) };
            });
        }
    }

    // 去重
    const seen = new Set();
    const unique = [];
    for (const ex of examples) {
        if (!seen.has(ex.ru)) { seen.add(ex.ru); unique.push(ex); }
    }

    // 补充
    if (unique.length < 2) {
        if (type === 'verb') {
            unique.push({ ru: `Мне нрáвится ${strip(word)} — э́то óчень полéзно.`, zh: `我喜欢${primary}——这非常有用。` });
        } else if (type === 'noun') {
            const g = gender === 'feminine' ? 'f' : gender === 'neuter' ? 'n' : 'm';
            unique.push({ ru: `Без ${declineNoun(word,g,'gen')} трýдно представи́ть себé жи́знь.`, zh: `没有${primary}的话，很难想象生活。` });
        } else {
            unique.push({ ru: `Э́то óчень ${strip(word)} — мне нрáвится.`, zh: `这非常${primary}——我很喜欢。` });
        }
    }

    return unique.slice(0, 3);
}

// ─── 文件重建 ──────────────────────────────────────────────────

function rebuildFrontmatter(examples, fm) {
    const lines = ['---'];
    const fieldOrder = ['word','type','theme','meaning','mastery','tags',
        'gender','animate','aspect','examples','created'];
    const written = new Set();

    for (const key of fieldOrder) {
        if (fm[key] === undefined) continue;
        written.add(key);
        if (key === 'examples') {
            lines.push('examples:');
            for (const ex of examples) {
                lines.push(`  - ru: "${ex.ru}"`);
                lines.push(`    zh: "${ex.zh}"`);
            }
        } else if (Array.isArray(fm[key])) {
            lines.push(`${key}: [${fm[key].map(v => `"${v}"`).join(', ')}]`);
        } else if (typeof fm[key] === 'string') {
            lines.push(`${key}: "${fm[key]}"`);
        } else {
            lines.push(`${key}: ${fm[key]}`);
        }
    }

    for (const [key, val] of Object.entries(fm)) {
        if (written.has(key)) continue;
        if (key === 'examples') {
            lines.push('examples:');
            for (const ex of examples) {
                lines.push(`  - ru: "${ex.ru}"`);
                lines.push(`    zh: "${ex.zh}"`);
            }
        } else if (typeof val === 'string') {
            lines.push(`${key}: "${val}"`);
        } else if (Array.isArray(val)) {
            lines.push(`${key}: [${val.map(v => `"${v}"`).join(', ')}]`);
        } else {
            lines.push(`${key}: ${val}`);
        }
    }

    lines.push('---');
    return lines.join('\n');
}

function rebuildBodyExamples(body, examples) {
    const tableLines = [
        '', '## ✍️ 例句', '',
        '| 俄语 | 中文 |',
        '|------|------|',
        ...examples.map(ex => `| ${ex.ru} | ${ex.zh} |`),
        ''
    ];
    const regex = /## ✍️ 例句[\s\S]*?(?=\n## |\n---|\n📚|\n📐|$)/;
    if (regex.test(body)) return body.replace(regex, tableLines.join('\n'));
    return body.trimEnd() + '\n' + tableLines.join('\n');
}

function parseFrontmatter(src) {
    const m = src.match(/^---\r?\n([\s\S]*?)\r?\n---/);
    if (!m) return {};
    const yaml = m[1];
    const result = {};
    let currentKey = null;
    let inArray = false;
    let arrayItems = [];
    let inObj = false;
    let objItem = {};

    for (const rawLine of yaml.split('\n')) {
        const line = rawLine.replace(/\r$/, '');
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) continue;

        if (/^\s+-\s+/.test(line)) {
            const itemStr = line.replace(/^\s+-\s+/, '').trim();
            if (itemStr.includes(':')) {
                const [k, ...rest] = itemStr.split(':');
                const v = rest.join(':').trim();
                objItem[k.trim()] = unquote(v);
                inObj = true;
            } else {
                if (inObj && Object.keys(objItem).length) { arrayItems.push({ ...objItem }); objItem = {}; inObj = false; }
                arrayItems.push(unquote(itemStr));
            }
            inArray = true;
            continue;
        }

        if (inArray && inObj && /^\s+\w[\w-]*:\s+/.test(line)) {
            const kv = line.match(/^\s+(\w[\w-]*):\s*(.*)/);
            if (kv) { objItem[kv[1]] = unquote(kv[2].trim()); continue; }
        }

        if (inArray) {
            if (inObj && Object.keys(objItem).length) { arrayItems.push({ ...objItem }); objItem = {}; inObj = false; }
            if (currentKey) result[currentKey] = arrayItems;
            arrayItems = []; inArray = false;
        }

        const kvMatch = line.match(/^(\w[\w-]*):\s*(.*)/);
        if (kvMatch) {
            currentKey = kvMatch[1];
            const val = kvMatch[2].trim();
            if (val === '' || val === '|' || val === '>') result[currentKey] = '';
            else if (val.startsWith('[') && val.endsWith(']')) result[currentKey] = parseInlineArray(val);
            else result[currentKey] = unquote(val);
            continue;
        }

        if (currentKey && /^\s+/.test(line) && !inArray) {
            const existing = result[currentKey];
            if (typeof existing === 'string') result[currentKey] = existing + ' ' + trimmed;
        }
    }

    if (inArray && currentKey) {
        if (inObj && Object.keys(objItem).length) arrayItems.push({ ...objItem });
        result[currentKey] = arrayItems;
    }

    return result;
}

function parseInlineArray(s) {
    s = s.trim();
    if (s.startsWith('[') && s.endsWith(']')) s = s.slice(1, -1);
    if (!s.trim()) return [];
    const items = [];
    let current = '';
    let inQ = false;
    let qC = '';
    for (let i = 0; i < s.length; i++) {
        const c = s[i];
        if (inQ) { if (c === qC) inQ = false; else current += c; }
        else { if (c === '"' || c === "'") { inQ = true; qC = c; } else if (c === ',') { items.push(current.trim()); current = ''; } else current += c; }
    }
    if (current.trim()) items.push(current.trim());
    return items.map(unquote);
}

function unquote(s) {
    if (typeof s !== 'string') return s;
    s = s.trim();
    if ((s.startsWith('"') && s.endsWith('"')) || (s.startsWith("'") && s.endsWith("'"))) return s.slice(1, -1);
    if (s === 'true') return true;
    if (s === 'false') return false;
    if (/^\d+$/.test(s)) return parseInt(s, 10);
    if (/^\d+\.\d+$/.test(s)) return parseFloat(s);
    return s;
}

// ─── 主流程 ──────────────────────────────────────────────────

function processFile(filePath) {
    const src = fs.readFileSync(filePath, 'utf-8');
    const fm = parseFrontmatter(src);
    if (!fm.word || !fm.meaning || !fm.type) return null;

    const examples = generateExamples(String(fm.type), String(fm.word), String(fm.meaning), fm.gender || '', fm.aspect || '');
    if (!examples || examples.length === 0) return null;

    const fmBlock = rebuildFrontmatter(examples, fm);
    const bodyStart = src.indexOf('---', 4) + 3;
    const body = src.slice(bodyStart);
    const newBody = rebuildBodyExamples(body, examples);

    fs.writeFileSync(filePath, fmBlock + '\n' + newBody, 'utf-8');
    return examples.length;
}

function walkMd(dir) {
    let results = [];
    if (!fs.existsSync(dir)) return results;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            if (['.obsidian', '.trash', '模板'].includes(entry.name)) continue;
            results = results.concat(walkMd(full));
        } else if (entry.name.endsWith('.md') && entry.name !== '章节索引.md') {
            results.push(full);
        }
    }
    return results;
}

function main() {
    console.log('🔄 开始重写词汇例句...');
    const files = walkMd(VOCAB_DIR);
    console.log(`   找到 ${files.length} 个 .md 文件\n`);

    let success = 0, skipped = 0, errors = 0;
    for (const f of files) {
        try {
            const count = processFile(f);
            if (count) success++;
            else skipped++;
        } catch (err) {
            console.warn(`   ⚠ ${path.relative(VAULT, f)}: ${err.message}`);
            errors++;
        }
    }

    console.log(`\n✅ 例句重写完成!`);
    console.log(`   成功: ${success}  跳过: ${skipped}  错误: ${errors}`);
}

main();
