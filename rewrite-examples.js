// ─── 名词变格 ──────────────────────────────────────────────────

function nounStem(word) {
    const w = strip(word);
    if (w.endsWith('а') || w.endsWith('я') || w.endsWith('о') || w.endsWith('е') || w.endsWith('ь')) return w.slice(0, -1);
    return w;
}

function declineNoun(word, gender, c) {
    const w = strip(word);
    const s = nounStem(word);
    if (c === 'nom') return word;
    if (c === 'acc') {
        if (gender === 'f' && w.endsWith('а')) return s + 'у';
        if (gender === 'f' && w.endsWith('я')) return s + 'ю';
        return word;
    }
    if (c === 'gen') {
        if (gender === 'f' && w.endsWith('а')) return s + 'ы';
        if (gender === 'f' && w.endsWith('я')) return s + 'и';
        if (gender === 'f' && w.endsWith('ь')) return s + 'и';
        if (gender === 'n' && w.endsWith('е')) return s + 'я';
        if (gender === 'n' && w.endsWith('о')) return s + 'а';
        if (gender === 'm') return word + 'а';
        return word + 'а';
    }
    if (c === 'dat') {
        if (gender === 'f' && (w.endsWith('а') || w.endsWith('я'))) return s + 'е';
        if (gender === 'f' && w.endsWith('ь')) return s + 'и';
        if (gender === 'n' && (w.endsWith('е') || w.endsWith('о'))) return s + 'ю';
        if (gender === 'm') return word + 'у';
        return word + 'у';
    }
    if (c === 'ins') {
        if (gender === 'f' && w.endsWith('а')) return s + 'ой';
        if (gender === 'f' && w.endsWith('я')) return s + 'ей';
        if (gender === 'f' && w.endsWith('ь')) return s + 'ью';
        if (gender === 'n' && (w.endsWith('е') || w.endsWith('о'))) return s + 'ем';
        return word + 'ом';
    }
    if (c === 'prep') {
        if (gender === 'f' && (w.endsWith('а') || w.endsWith('я'))) return s + 'е';
        if (gender === 'f' && w.endsWith('ь')) return s + 'и';
        if (gender === 'n' && (w.endsWith('е') || w.endsWith('о'))) return s + 'и';
        return word + 'е';
    }
    return word;
}

function declineAdj(word, gender, c) {
    const w = strip(word);
    let b;
    if (w.endsWith('ый')) b = w.slice(0, -2);
    else if (w.endsWith('ой')) b = w.slice(0, -2);
    else if (w.endsWith('ий')) b = w.slice(0, -2);
    else b = w.slice(0, -2);

    if (c === 'nom') return gender === 'm' ? b+'ый' : gender === 'f' ? b+'ая' : gender === 'n' ? b+'ое' : b+'ые';
    if (c === 'acc') return gender === 'm' ? b+'ый' : gender === 'f' ? b+'ую' : gender === 'n' ? b+'ое' : b+'ые';
    if (c === 'gen') return (gender==='m'||gender==='n') ? b+'ого' : gender==='f' ? b+'ой' : b+'ых';
    if (c === 'dat') return (gender==='m'||gender==='n') ? b+'ому' : gender==='f' ? b+'ой' : b+'ым';
    if (c === 'ins') return (gender==='m'||gender==='n') ? b+'ым' : gender==='f' ? b+'ой' : b+'ыми';
    if (c === 'prep') return (gender==='m'||gender==='n') ? b+'ом' : gender==='f' ? b+'ой' : b+'ых';
    return word;
}

// ─── 伪随机 ──────────────────────────────────────────────────

function hashStr(s) {
    let h = 0;
    for (let i = 0; i < s.length; i++) h = ((h << 5) - h + s.charCodeAt(i)) | 0;
    return Math.abs(h);
}

function pickN(arr, n, seed) {
    const shuffled = [...arr];
    let h = seed;
    for (let i = shuffled.length - 1; i > 0; i--) {
        h = (h * 1103515245 + 12345) & 0x7fffffff;
        const j = h % (i + 1);
        [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
    }
    return shuffled.slice(0, n);
}

