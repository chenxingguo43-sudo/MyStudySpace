function applyStress(word) {
    if (!word) return word;
    // 先检查字典
    var lower = word.toLowerCase();
    if (STRESS_DICT[lower]) {
        // 保持首字母大小写
        var stressed = STRESS_DICT[lower];
        if (word[0] === word[0].toUpperCase()) {
            stressed = stressed[0].toUpperCase() + stressed.slice(1);
        }
        return stressed;
    }
    return word; // 不在字典中，返回原词
}

// ─── 例句模板 ────────────────────────────────────────────────

function generateExamples(fm, type) {
    var word = fm.word || '';
    var meaning = fm.meaning || '';
    var examples = [];

    if (type === 'noun') {
        var gender = fm.gender || '';
        var wStressed = applyStress(word);
        // 根据名词性别选择动词搭配
        if (gender === 'masculine' || gender === 'feminine' || gender === 'neuter') {
            examples.push({
                ru: 'Э́тот ' + wStressed + ' о́чень ва́жен.',
                zh: '这个' + meaning.split('；')[0] + '非常重要。'
            });
            examples.push({
                ru: 'Я ви́жу ' + getAccusative(word, gender) + '.',
                zh: '我看见' + meaning.split('；')[0] + '。'
            });
        } else {
            examples.push({
                ru: 'Э́тот ' + wStressed + ' о́чень ва́жен.',
                zh: '这个' + meaning.split('；')[0] + '非常重要。'
            });
        }
    } else if (type === 'verb') {
        var wStressed = applyStress(word);
        examples.push({
            ru: 'Я хотéл бы ' + wStressed + '.',
            zh: '我想' + meaning.split('；')[0] + '。'
        });
        examples.push({
            ru: 'Он ча́сто ' + getVerb3sg(word) + '.',
            zh: '他经常' + meaning.split('；')[0] + '。'
        });
    } else if (type === 'adj') {
        var wStressed = applyStress(word);
        examples.push({
            ru: 'Э́то о́чень ' + wStressed + ' предме́т.',
            zh: '这是一个很' + meaning.split('；')[0] + '的东西。'
        });
    } else if (type === 'adv') {
        var wStressed = applyStress(word);
        examples.push({
            ru: 'Он ' + wStressed + ' говори́т.',
            zh: '他' + meaning.split('；')[0] + '地说。'
        });
    }

    return examples;
}

// 简单的名词变格（宾格形式）
function getAccusative(word, gender) {
    var stressed = applyStress(word);
    if (gender === 'masculine') {
        // 阳性：有生命 -а/-я，无生命 不变
        return stressed; // 简化处理
    } else if (gender === 'feminine') {
        // 阴性：-а → -у, -я → -ю
        if (stressed.endsWith('а')) return stressed.slice(0, -1) + 'у';
        if (stressed.endsWith('я')) return stressed.slice(0, -1) + 'ю';
        return stressed;
    } else if (gender === 'neuter') {
        // 中性：不变
        return stressed;
    }
    return stressed;
}

// 简单的动词第三人称单数
function getVerb3sg(word) {
    var stressed = applyStress(word);
    // -ть → -ет/-ит (简化)
    if (stressed.endsWith('ать')) return stressed.slice(0, -3) + 'ает';
    if (stressed.endsWith('ить')) return stressed.slice(0, -3) + 'ит';
    if (stressed.endsWith('еть')) return stressed.slice(0, -3) + 'еет';
    if (stressed.endsWith('ять')) return stressed.slice(0, -3) + 'яет';
    if (stressed.endsWith('уть')) return stressed.slice(0, -3) + 'ует';
    return stressed;
}

// ─── 主处理 ─────────────────────────────────────────────────

function processFile(filePath) {
    var content = fs.readFileSync(filePath, 'utf8');
    var parsed = parseFrontmatter(content);
    var fm = parsed.fm;
    var body = parsed.body;

    if (!fm.word) return null;

    var type = fm.type || '';
    var word = fm.word;

    // 1. 更新 frontmatter 中的 word 为带重音形式
    var stressedWord = applyStress(word);
    fm.word = stressedWord;

    // 2. 生成例句（如果空）
    var existingExamples = fm.examples || [];
    var hasRealExamples = existingExamples.some(function(ex) {
        return ex && ex.ru && ex.ru.trim() !== '';
    });
    if (!hasRealExamples) {
        fm.examples = generateExamples(fm, type);
    }

    // 3. 更新 frontmatter 中的 meaning 加重音
    // (meaning 是中文，不需要重音)

    // 4. 重建 markdown
    var newFm = buildFrontmatter(fm, type);
    var newBody = buildBody(fm, type, body);

    return newFm + newBody;
}

function buildFrontmatter(fm, type) {
    var lines = ['---'];
    lines.push('word: ' + yamlString(fm.word));
    lines.push('type: ' + yamlString(fm.type || ''));
    if (fm.theme) lines.push('theme: ' + yamlString(fm.theme));
    lines.push('meaning: ' + yamlString(fm.meaning || ''));
    lines.push('mastery: ' + (fm.mastery || 1));
    lines.push('tags: ' + yamlArray(fm.tags || []));

    if (type === 'noun') {
        if (fm.gender) lines.push('gender: ' + yamlString(fm.gender));
        if (fm.animate !== undefined) lines.push('animate: ' + fm.animate);
        if (fm.plural_gen) lines.push('plural_gen: ' + yamlString(fm.plural_gen));
    } else if (type === 'verb') {
        if (fm.aspect) lines.push('aspect: ' + yamlString(fm.aspect));
        if (fm.pair) lines.push('pair: ' + yamlString(fm.pair));
        if (fm.case_gov) lines.push('case_gov: ' + yamlString(fm.case_gov));
        if (fm.conj_pattern) lines.push('conj_pattern: ' + yamlString(fm.conj_pattern));
    } else if (type === 'adj') {
        if (fm.short_form) lines.push('short_form: ' + yamlString(fm.short_form));
        if (fm.comparative) lines.push('comparative: ' + yamlString(fm.comparative));
    }

    lines.push('examples:');
    lines.push(yamlExamples(fm.examples || []));
    lines.push('created: ' + yamlString(fm.created || new Date().toISOString().slice(0, 10)));
    lines.push('---');
    return lines.join('\n');
}

function buildBody(fm, type, oldBody) {
    var word = fm.word;
    var meaning = fm.meaning || '';

    var md = '\n\n# ' + word + '\n\n';
    md += '## 📖 释义\n' + meaning + '\n\n';

    // 例句
    md += '## ✍️ 例句\n\n';
    md += '| 俄语 | 中文 |\n|------|------|\n';
    (fm.examples || []).forEach(function(ex) {
        if (ex && ex.ru) {
            md += '| ' + ex.ru + ' | ' + (ex.zh || '') + ' |\n';
        }
    });
    md += '\n';

    // 变格/变位表
    md += '## 📐 变位/变格/接格\n';
    if (type === 'noun') {
        md += generateNounDeclension(fm);
    } else if (type === 'verb') {
        md += generateVerbConjugation(fm);
    } else if (type === 'adj') {
        md += generateAdjDeclension(fm);
    } else {
        md += '- 不适用\n';
    }
    md += '\n';

    // 相关词
    md += '## 📚 相关词\n';
    if (fm.pair) md += '- 配对: [[' + fm.pair + ']]\n';
    md += '- [[' + word + ']]\n';

    return md;
}

