function walkMd(dir) {
    let results = [];
    try {
        fs.readdirSync(dir).forEach(f => {
            const fp = path.join(dir, f);
            if (fs.statSync(fp).isDirectory()) results = results.concat(walkMd(fp));
            else if (f.endsWith('.md')) results.push(fp);
        });
    } catch(e) {}
    return results;
}

function parseFrontmatter(src) {
    const m = src.match(/^---\r?\n([\s\S]*?)\r?\n---/);
    if (!m) return { fm: {}, body: src };
    return { fm: parseYaml(m[1]), body: src.slice(m[0].length), rawFm: m[1] };
}

function parseYaml(yaml) {
    const result = {};
    let currentKey = null;
    let inArray = false;
    let arrayItems = [];
    let inObj = false;
    let objItem = {};

    for (const rawLine of yaml.split('\n')) {
        const line = rawLine.replace(/\r$/, '');
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) continue;

        if (/^\s+-\s+/.test(line)) {
            const itemStr = line.replace(/^\s+-\s+/, '').trim();
            if (itemStr.includes(':')) {
                const [k, ...rest] = itemStr.split(':');
                const v = rest.join(':').trim();
                objItem[k.trim()] = unquote(v);
                inObj = true;
            } else {
                if (inObj && Object.keys(objItem).length) {
                    arrayItems.push({ ...objItem });
                    objItem = {};
                    inObj = false;
                }
                arrayItems.push(unquote(itemStr));
            }
            inArray = true;
            continue;
        }

        if (inArray && inObj && /^\s+\w[\w-]*:\s+/.test(line)) {
            const kvMatch = line.match(/^\s+(\w[\w-]*):\s*(.*)/);
            if (kvMatch) {
                objItem[kvMatch[1]] = unquote(kvMatch[2].trim());
                continue;
            }
        }

        if (inArray) {
            if (inObj && Object.keys(objItem).length) {
                arrayItems.push({ ...objItem });
                objItem = {};
                inObj = false;
            }
            if (currentKey) result[currentKey] = arrayItems;
            arrayItems = [];
            inArray = false;
        }

        const kvMatch = trimmed.match(/^(\w[\w-]*):\s*(.*)/);
        if (kvMatch) {
            currentKey = kvMatch[1];
            const val = kvMatch[2].trim();
            if (val === '' || val === '|' || val === '>') {
                // multi-line, skip
            } else {
                result[currentKey] = unquote(val);
            }
        }
    }
    if (inArray) {
        if (inObj && Object.keys(objItem).length) arrayItems.push({ ...objItem });
        if (currentKey) result[currentKey] = arrayItems;
    }
    return result;
}

function unquote(s) {
    if (!s) return s;
    s = s.trim();
    // Handle inline JSON arrays: ["B2", "词汇"]
    if (s.startsWith('[') && s.endsWith(']')) {
        try { return JSON.parse(s); } catch(e) {}
    }
    if ((s.startsWith('"') && s.endsWith('"')) || (s.startsWith("'") && s.endsWith("'"))) return s.slice(1, -1);
    return s;
}

function yamlString(v) {
    if (typeof v !== 'string') return String(v);
    if (/[:#{}[\],&*?|>!%@`]/.test(v) || v === '' || v.includes('\n')) return '"' + v.replace(/"/g, '\\"') + '"';
    return v;
}

function yamlArray(arr) {
    if (!arr) return '[]';
    if (typeof arr === 'string') return arr; // already a string representation
    if (!Array.isArray(arr)) return '[]';
    if (!arr.length) return '[]';
    if (arr.length <= 3 && arr.every(x => typeof x === 'string' && !x.includes(','))) {
        return '[' + arr.map(x => '"' + x + '"').join(', ') + ']';
    }
    return arr.map(x => {
        if (typeof x === 'object') {
            const keys = Object.keys(x);
            return '- ' + keys.map(k => k + ': ' + yamlString(x[k])).join('\n  ');
        }
        return '- ' + yamlString(x);
    }).join('\n');
}

function yamlExamples(arr) {
    if (!arr) return '  - ru: ""\n    zh: ""';
    if (typeof arr === 'string') return '  - ru: ""\n    zh: ""';
    if (!Array.isArray(arr)) return '  - ru: ""\n    zh: ""';
    if (!arr.length) return '  - ru: ""\n    zh: ""';
    return arr.map(ex => {
        if (typeof ex === 'string') return '  - ru: ' + yamlString(ex) + '\n    zh: ""';
        return '  - ru: ' + yamlString(ex.ru || '') + '\n    zh: ' + yamlString(ex.zh || '');
    }).join('\n');
}

