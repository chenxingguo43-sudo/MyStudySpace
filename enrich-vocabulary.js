function main() {
    console.log('📚 词汇充实工具');
    console.log('================\n');

    var files = walkMd(VAULT).filter(function(f) {
        return !f.includes('protocol');
    });

    if (TYPE_FILTER) {
        var typeDir = TYPE_FILTER === 'noun' ? '名词' :
            TYPE_FILTER === 'verb' ? '动词' :
            TYPE_FILTER === 'adj' ? '形容词' :
            TYPE_FILTER === 'adv' ? '副词' : TYPE_FILTER;
        files = files.filter(function(f) { return f.includes(typeDir); });
    }

    files = files.slice(0, LIMIT);
    console.log('处理文件: ' + files.length + ' 个\n');

    var processed = 0;
    var skipped = 0;
    var errors = 0;

    files.forEach(function(f) {
        try {
            var result = processFile(f);
            if (result) {
                if (DRY_RUN) {
                    console.log('[DRY] ' + path.basename(f));
                } else {
                    fs.writeFileSync(f, result, 'utf8');
                    processed++;
                    if (processed % 50 === 0) console.log('  已处理: ' + processed);
                }
            } else {
                skipped++;
            }
        } catch(e) {
            errors++;
            console.error('❌ ' + path.basename(f) + ': ' + e.message);
        }
    });

    console.log('\n✅ 完成: 处理 ' + processed + ', 跳过 ' + skipped + ', 错误 ' + errors);
}

main();
